import { chromium } from "playwright-core";
import fs from "node:fs";
const OUT = new URL("./out/", import.meta.url).pathname.replace(/^\/([A-Z]:)/, "$1");
fs.mkdirSync(OUT, { recursive: true });
const b = await chromium.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe" });
const ctx = await b.newContext({ viewport: { width: 1446, height: 800 } });
const page = await ctx.newPage();
const errs = []; page.on("pageerror", (e) => errs.push(e.message));
await ctx.addInitScript(() => localStorage.setItem("gl:theme", "dark"));
await page.goto("http://localhost:3000/live", { waitUntil: "networkidle", timeout: 90000 });
await page.waitForTimeout(2500);
const trigger = page.getByRole("button", { name: /Choose a caller|·/ }).filter({ has: page.locator("svg") }).first();
const nameOnButton = async () => (await page.locator('button[aria-haspopup="listbox"]').innerText()).replace(/\s+/g, " ");
console.log("closed button:", await nameOnButton());
await page.locator('button[aria-haspopup="listbox"]').click();
await page.waitForTimeout(400);
console.log("options:", await page.getByRole("option").count());
await page.screenshot({ path: `${OUT}picker-open-dark.png` });
await page.getByLabel("Search callers").fill("ash");
await page.waitForTimeout(300);
console.log("search 'ash' ->", (await page.getByRole("option").allInnerTexts()).map((t) => t.replace(/\s+/g, " ")));
await page.screenshot({ path: `${OUT}picker-search-dark.png` });
await page.getByLabel("Search callers").fill("zzzz");
console.log("no match text:", await page.getByText(/No caller matches/).count());
await page.getByLabel("Search callers").fill("piy");
await page.keyboard.press("Enter");
await page.waitForTimeout(2500);
console.log("after Enter on 'piy':", await nameOnButton(), "| listbox closed:", (await page.getByRole("listbox").count()) === 0);
console.log("heading:", (await page.locator("h1, h2").first().innerText()).slice(0, 40));
await page.locator('button[aria-haspopup="listbox"]').click();
await page.keyboard.press("Escape");
console.log("Escape closes:", (await page.getByRole("listbox").count()) === 0);
console.log("errors:", errs.length ? errs : "none");
await b.close();
